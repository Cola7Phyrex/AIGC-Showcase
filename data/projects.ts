export type ProjectStatus = "已完成" | "可体验" | "开发中";
export type StatusTone = "complete" | "available" | "building";
export type MediaOrientation = "landscape" | "portrait";

export type ProjectMedia = {
  id: string;
  kind: "image" | "video";
  orientation: MediaOrientation;
  label: string;
  src?: string;
  alt?: string;
  aspectRatio?: string;
  layout?: "full" | "tile" | "contained" | "pair" | "triplet" | "quartet";
};

export type ProjectLink = {
  label: string;
  kind: "website" | "video" | "repository";
  url: string | null;
};

export type ProjectFile = {
  label: string;
  fileName: string;
  fileSize: string;
  url: string | null;
};

export type Project = {
  order: number;
  slug: string;
  title: string;
  type: string;
  category: string;
  platforms: string[];
  coreTool: string;
  auxiliaryTools: string[];
  description: string;
  highlight: string;
  status: ProjectStatus;
  statusTone: StatusTone;
  accent: string;
  accentSecondary: string;
  coverImage?: string;
  coverAlt?: string;
  media: ProjectMedia[];
  links: ProjectLink[];
  files: ProjectFile[];
};

type ProjectDraft = Omit<Project, "media" | "links" | "files"> & {
  media?: ProjectMedia[];
  links?: ProjectLink[];
  files?: ProjectFile[];
};

function createProject(project: ProjectDraft): Project {
  return {
    ...project,
    media: project.media ?? [
      {
        id: `${project.slug}-hero`,
        kind: "video",
        orientation: "landscape",
        label: "横版视频 / 主演示画面",
      },
      {
        id: `${project.slug}-portrait-a`,
        kind: "image",
        orientation: "portrait",
        label: "竖版截图 01",
      },
      {
        id: `${project.slug}-portrait-b`,
        kind: "image",
        orientation: "portrait",
        label: "竖版截图 02",
      },
      {
        id: `${project.slug}-wide`,
        kind: "image",
        orientation: "landscape",
        label: "横版截图 / 制作过程",
      },
    ],
    links: project.links ?? [
      { label: "在线体验", kind: "website", url: null },
      { label: "演示视频", kind: "video", url: null },
      { label: "代码仓库", kind: "repository", url: null },
    ],
    files: project.files ?? [
      {
        label: "项目源文件",
        fileName: "source-file-placeholder.zip",
        fileSize: "待上传",
        url: null,
      },
    ],
  };
}

